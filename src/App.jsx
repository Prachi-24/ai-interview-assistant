import { useState, useEffect } from "react";
import "./App.css";

function App() {
  const [resume, setResume] = useState(null);
  const [jobDescription, setJobDescription] = useState("");
  const [question, setQuestion] = useState("");

  const [isUploading, setIsUploading] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [uploadMessage, setUploadMessage] = useState("");
  const [resumeUploaded, setResumeUploaded] = useState(false);

  const [activeChatId, setActiveChatId] = useState(null);

  const [chats, setChats] = useState(() => {
    try {
      return JSON.parse(localStorage.getItem("interviewAIChats") || "[]");
    } catch {
      return [];
    }
  });

  const [activePage, setActivePage] = useState("Dashboard");

  // Save chat history in localStorage
  useEffect(() => {
    localStorage.setItem("interviewAIChats", JSON.stringify(chats));
  }, [chats]);

  // Get the currently selected conversation
  const activeChat = chats.find((chat) => chat.id === activeChatId);

  // Start a new conversation
  function startNewChat() {
    setActiveChatId(null);
    setQuestion("");
    setActivePage("Dashboard");
  }

  // Open an existing conversation
  function openChat(chatId) {
    setActiveChatId(chatId);
    setActivePage("Dashboard");
  }

  // Upload the resume to FastAPI
  async function uploadResume() {
    if (!resume) {
      setUploadMessage("Please select a PDF resume first.");
      return;
    }

    const formData = new FormData();
    formData.append("file", resume);

    setIsUploading(true);
    setUploadMessage("");
    setResumeUploaded(false);

    try {
      const response = await fetch("http://127.0.0.1:8000/upload-resume", {
        method: "POST",
        body: formData,
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.detail || "Resume upload failed.");
      }

      setResumeUploaded(true);

      setUploadMessage(
        `Resume uploaded successfully! ${data.total_chunks} chunks created.`,
      );
    } catch (error) {
      setUploadMessage(error.message || "Could not connect to the backend.");
    } finally {
      setIsUploading(false);
    }
  }

  // Send a question to the RAG backend
  async function sendMessage(event) {
    event.preventDefault();

    const text = question.trim();

    if (!text || isLoading) {
      return;
    }

    if (!resumeUploaded) {
      alert("Please upload your resume before asking questions.");
      return;
    }

    const chatId = activeChatId || Date.now();

    const existingChat = chats.find((chat) => chat.id === chatId);

    const userMessage = {
      id: Date.now(),
      role: "user",
      text,
    };

    // Add the user's question to chat history
    if (existingChat) {
      setChats((previousChats) =>
        previousChats.map((chat) =>
          chat.id === chatId
            ? {
                ...chat,
                messages: [...chat.messages, userMessage],
              }
            : chat,
        ),
      );
    } else {
      setChats((previousChats) => [
        {
          id: chatId,
          title: text.slice(0, 35),
          messages: [userMessage],
        },
        ...previousChats,
      ]);
    }

    setActiveChatId(chatId);
    setQuestion("");
    setIsLoading(true);

    try {
      // Send the question to FastAPI
      const response = await fetch("http://127.0.0.1:8000/ask", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          question: text,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.detail || "Failed to get an answer.");
      }

      // Receive the answer generated by Ollama
      const aiMessage = {
        id: Date.now() + 1,
        role: "assistant",
        text: data.answer,
      };

      // Add the AI answer to chat history
      setChats((previousChats) =>
        previousChats.map((chat) =>
          chat.id === chatId
            ? {
                ...chat,
                messages: [...chat.messages, aiMessage],
              }
            : chat,
        ),
      );
    } catch (error) {
      // Display an error in the conversation
      const errorMessage = {
        id: Date.now() + 1,
        role: "assistant",
        text: `Sorry, something went wrong: ${error.message}`,
      };

      setChats((previousChats) =>
        previousChats.map((chat) =>
          chat.id === chatId
            ? {
                ...chat,
                messages: [...chat.messages, errorMessage],
              }
            : chat,
        ),
      );
    } finally {
      setIsLoading(false);
    }
  }

  return (
    <div className="app">
      {/* Sidebar */}
      <aside className="sidebar">
        <h2>InterviewAI</h2>

        <button className="new-chat" onClick={startNewChat}>
          + New Chat
        </button>

        <nav>
          <button
            className={
              activePage === "Dashboard" ? "nav-item active" : "nav-item"
            }
            onClick={() => setActivePage("Dashboard")}
          >
            🏠 Dashboard
          </button>

          <button
            className={
              activePage === "Interview Practice"
                ? "nav-item active"
                : "nav-item"
            }
            onClick={() => setActivePage("Interview Practice")}
          >
            🎯 Interview Practice
          </button>
        </nav>

        {/* Chat history */}
        <div className="history">
          <h3>🕘 Chat History</h3>

          {chats.length === 0 ? (
            <p className="empty-history">
              Your conversations will appear here.
            </p>
          ) : (
            chats.map((chat) => (
              <button
                key={chat.id}
                className={
                  activeChatId === chat.id
                    ? "history-item selected"
                    : "history-item"
                }
                onClick={() => openChat(chat.id)}
                title={chat.title}
              >
                {chat.title}
              </button>
            ))
          )}
        </div>

        <p className="sidebar-footer">Your AI Interview Assistant</p>
      </aside>

      {/* Main content */}
      <main className="main-content">
        <header className="header">
          <h2>AI Interview Assistant</h2>
          <p>Prepare smarter. Interview with confidence.</p>
        </header>

        {activePage === "Dashboard" ? (
          <>
            {/* Welcome section */}
            <section className="welcome">
              <h1>Welcome to InterviewAI 👋</h1>

              <p>
                Upload your resume and practise for your next interview with
                your AI assistant.
              </p>
            </section>

            {/* Resume upload */}
            <section className="card">
              <h3>📄 Upload Your Resume</h3>

              <p>Select your resume in PDF format.</p>

              <input
                type="file"
                accept=".pdf,application/pdf"
                onChange={(event) => {
                  const file = event.target.files?.[0];

                  if (
                    file &&
                    (file.type === "application/pdf" ||
                      file.name.toLowerCase().endsWith(".pdf"))
                  ) {
                    setResume(file);
                    setResumeUploaded(false);
                    setUploadMessage("");
                  } else {
                    setResume(null);
                    setResumeUploaded(false);
                    setUploadMessage("Please select a valid PDF file.");
                  }
                }}
              />

              {resume && <p className="success">Selected: {resume.name}</p>}

              <button
                className="primary-button"
                onClick={uploadResume}
                disabled={!resume || isUploading}
              >
                {isUploading ? "Uploading..." : "Upload Resume"}
              </button>

              {uploadMessage && (
                <p className={resumeUploaded ? "success" : "upload-message"}>
                  {uploadMessage}
                </p>
              )}
            </section>

            {/* Job description */}
            <section className="card">
              <h3>💼 Target Job Description</h3>

              <p>Enter the job role or paste its description.</p>

              <textarea
                placeholder="Example: Associate Data Scientist — Python, SQL, Machine Learning..."
                value={jobDescription}
                onChange={(event) => setJobDescription(event.target.value)}
              />
            </section>

            {/* Chat section */}
            <section className="card">
              <h3>💬 {activeChat ? activeChat.title : "AI Interview Chat"}</h3>

              <div className="messages">
                {!activeChat || activeChat.messages.length === 0 ? (
                  <div className="chat-message">
                    <strong>AI Assistant</strong>

                    <p>
                      Hello! Ask me about your resume or practise interview
                      questions.
                    </p>
                  </div>
                ) : (
                  activeChat.messages.map((message) => (
                    <div
                      key={message.id}
                      className={`chat-message ${message.role}`}
                    >
                      <strong>
                        {message.role === "user" ? "You" : "AI Assistant"}
                      </strong>

                      <p>{message.text}</p>
                    </div>
                  ))
                )}
              </div>

              {/* Thinking indicator */}
              {isLoading && (
                <div className="chat-message assistant">
                  <strong>AI Assistant</strong>
                  <p>Thinking...</p>
                </div>
              )}

              {/* Chat input */}
              <form className="chat-input" onSubmit={sendMessage}>
                <input
                  type="text"
                  placeholder="Ask a question..."
                  value={question}
                  onChange={(event) => setQuestion(event.target.value)}
                />

                <button type="submit" disabled={isLoading}>
                  {isLoading ? "Thinking..." : "Send"}
                </button>
              </form>
            </section>
          </>
        ) : (
          <section className="card">
            <h2>Interview Practice 🎯</h2>

            <p>
              Practise technical and HR interview questions based on your resume
              and target job.
            </p>

            <button className="primary-button" onClick={startNewChat}>
              Start Practising
            </button>
          </section>
        )}
      </main>
    </div>
  );
}

export default App;
